//   1. Generate key pair baru: build/tools/keygen private.pem public.pem
//   2. Convert ke DER: openssl pkey -pubin -in public.pem -outform DER -out public.der
//   3. Baca bytes: xxd -p public.der
//   4. Salin byte array di bawah ini.
//   5. Update PUBLIC_KEY_DER_LEN sesuai jumlah byte.
